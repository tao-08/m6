-- =====================================================================
--  楽器に Acc（アコーディオン）を追加する
-- =====================================================================
--  083_studio.sql まで流した DB に、追加で流す。084_instrument_color.sql（楽器の色）より前でも後でも流せる。
--  （これから新しく作る人は schema.sql に含まれているので不要）
--
--  039（Prog）・040（Harm）と同じ作り。
--    ・id は自動採番（名簿の取り込みで「その他」から足された楽器と id がぶつからないように）
--    ・並び順（sort_order）は Harm の次の 12。「その他（etc）」は 99 のままなので、いちばん最後に出る
--    ・色（instrument.color）は入れない → NULL ＝ グレー。色は楽器の管理ページ（instruments.php）で変更できる
--      （列の名前を書いて INSERT しているので、color 列がまだ無い DB でも、もう有る DB でも同じように動く）
--
--  なぜ INSERT IGNORE ではなく、INSERT ... SELECT ... WHERE NOT EXISTS なのか
--    → 名簿の取り込みで、すでに「アコーディオン」が別の略称で足されているかもしれない（本番の中身は見えない）。
--      INSERT IGNORE は略称（short_name の UNIQUE）だけを見るので、名前が同じ行があっても足してしまい、
--      「アコーディオン」が2つ並んでしまう。そこで「略称 Acc も、名前 アコーディオン も無いときだけ」足す。
--      すでに別の略称であるときは、足さずに終わる（楽器の管理ページで略称を Acc に直せばよい）
-- =====================================================================

INSERT INTO instrument (name, short_name, sort_order)
SELECT 'アコーディオン', 'Acc', 12
FROM DUAL
WHERE NOT EXISTS (
    SELECT 1 FROM instrument WHERE short_name = 'Acc' OR name = 'アコーディオン'
);
