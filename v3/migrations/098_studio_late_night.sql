-- =====================================================================
--  098_studio_late_night.sql — スタジオに「深夜早朝」ラベルの印を付ける列
-- =====================================================================
--  深夜・早朝に使える（深夜早朝料金・無人営業など）スタジオに、一覧と詳細でラベルを出す。おすすめ（096）と同じく、編集できる人が手で付ける
--  ★ このSQLを本番DBで流してから、コードをデプロイすること（先にデプロイすると、スタジオ一覧が開けなくなる）
-- =====================================================================
ALTER TABLE studio
    ADD COLUMN late_night TINYINT(1) UNSIGNED NOT NULL DEFAULT 0 COMMENT '1=深夜早朝（一覧・詳細にラベルを出す）' AFTER recommended;
