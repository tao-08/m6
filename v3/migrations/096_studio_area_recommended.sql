-- =====================================================================
--  096_studio_area_recommended.sql — スタジオに「エリア」と「おすすめ」を足す
-- =====================================================================
--  area        … 一覧のエリア絞り込み用の名前（例: 新宿・明大前）。幹部がスタジオの編集で入力する。未入力は NULL（絞り込みに出ない）
--  recommended … 1 = おすすめ。幹部が付けると、一覧のカードにラベルが出る
--  ★ このSQLを本番DBで流してから、コードをデプロイすること（先にデプロイすると、スタジオの一覧が開けなくなる）
-- =====================================================================
ALTER TABLE studio
    ADD COLUMN area VARCHAR(30) NULL COMMENT '一覧のエリア絞り込み用（例: 新宿）' AFTER access,
    ADD COLUMN recommended TINYINT(1) UNSIGNED NOT NULL DEFAULT 0 COMMENT '1=おすすめ（一覧のカードにラベルを出す）' AFTER area;
