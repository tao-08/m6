-- =====================================================================
--  091_studio_room_half.sql — 部屋ごとの「30分スタート」「30分単位の利用」の設定
-- =====================================================================
--  half_start … 1 = 30分から始められる（9:30 開始など） / 0 = 毎時ちょうどだけ（9:00・10:00 …）
--  half_unit  … 1 = 利用時間を30分刻みで取れる（2.5時間など） / 0 = 1時間単位（2時間・3時間 …）
--  どちらも既定は 1（今までと同じ「30分きざみ」の動き）。1時間単位の部屋だけ、画面の「部屋を編集」で外す。
--  使い道: 料金シミュレーションの「開始」「時間」の選択肢と計算。部屋の見出しには、外している設定だけ小さく出す。
--  TINYINT(1) = 0/1 を入れる小さな整数（MySQL/MariaDB に真偽値専用の型は無く、これが慣習）
--  ★ このSQLを本番DBで流してから、コードをデプロイすること（先にデプロイすると部屋の SELECT が列なしで失敗する）
-- =====================================================================
ALTER TABLE studio_room
    ADD COLUMN half_start TINYINT(1) UNSIGNED NOT NULL DEFAULT 1 COMMENT '1=30分スタート可' AFTER size_note,
    ADD COLUMN half_unit  TINYINT(1) UNSIGNED NOT NULL DEFAULT 1 COMMENT '1=30分単位で利用可' AFTER half_start;
