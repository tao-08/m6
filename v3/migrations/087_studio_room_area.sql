-- =====================================================================
--  087_studio_room_area.sql — 部屋の広さを「数値（帖）」の列に分ける（検索・絞り込み用）
-- =====================================================================
--  今までの size_note（自由記述: "22帖・ビッグバンド対応" "9畳・最大5人（2階）"）は、
--  単位も書き方もバラバラで「12帖以上の部屋」のような検索ができなかった。
--  → area_jo（数値・単位は帖）を追加。size_note は定員・階数などの「備考」専用にする。
--
--  ■ なぜ「帖」か
--    スタジオの公式サイトは「帖」「畳」表記が大半（1帖 = 1畳として扱う）。㎡にすると換算誤差が出て、公式の数字とズレる。
--  ■ DECIMAL(5,1) とは
--    全5桁・小数1桁の「誤差が出ない小数」（0.0〜9999.9）。FLOAT は 0.1 のような値がわずかにズレるので、検索の比較には向かない。
--
--  実行順: 086 → （studio_fill_4.sql）→ 087
--    087 の後半は、すでに入っている size_note の先頭の数字（"22帖"）を area_jo に移す処理。
--    studio_fill_4.sql を 087 より後で流し直したときは、後半の UPDATE だけもう一度流す（何度流しても同じ結果になる）。
-- =====================================================================

-- ① 列を追加（NULL = 広さ不明）。UNSIGNED = マイナス不可
ALTER TABLE studio_room
    ADD COLUMN area_jo DECIMAL(5,1) UNSIGNED NULL COMMENT '広さ（帖）' AFTER name;

-- ② 既存データの移行（MariaDB 10.6 の正規表現関数を使用）
--   対象: size_note が「数字＋帖 or 畳」で始まる行（例: 22帖・ビッグバンド対応）
--   area_jo   … 先頭の数字（REGEXP_SUBSTR = 正規表現に合う部分を取り出す）
--   size_note … 先頭の「22帖」と、続く区切り（「・」や空白）を取り除いた残り（REGEXP_REPLACE）。空になったら NULL（NULLIF）
--   ※ TRIM(BOTH '・ ' FROM …) は「・␣という文字列まるごと」しか削らない（文字の集合ではない）ので使わず、正規表現で区切りごと消す
--   ※ UPDATE の SET は左から順に評価される。area_jo を先に書くのは、size_note を書き換える前の値から数字を取るため
UPDATE studio_room
   SET area_jo   = CAST(REGEXP_SUBSTR(size_note, '^[0-9]+([.][0-9]+)?') AS DECIMAL(5,1)),
       size_note = NULLIF(TRIM(REGEXP_REPLACE(size_note, '^[0-9]+([.][0-9]+)?[ ]*(帖|畳)[・ ]*', '')), '')
 WHERE size_note REGEXP '^[0-9]+([.][0-9]+)?[ ]*(帖|畳)';
