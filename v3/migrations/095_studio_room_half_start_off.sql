-- =====================================================================
--  095_studio_room_half_start_off.sql — 「30分開始」の既定をオフにする
-- =====================================================================
--  half_start = 1 の部屋は「毎時30分から始まる部屋」として、料金表・パックの時間帯を30分遅らせて表示・計算する
--  既定が 1 のままだと、今ある部屋が全部ずれるので、既定を 0 にして、今ある部屋も 0 に戻す
--  ★ 30分開始の部屋は、このSQLのあと、画面の「部屋を編集」で 30分開始 を入れ直すこと
--  ★ このSQLを本番DBで流してから、コードをデプロイすること（流さないと全部の部屋が30分遅れで表示される）
-- =====================================================================
ALTER TABLE studio_room
    MODIFY COLUMN half_start TINYINT(1) UNSIGNED NOT NULL DEFAULT 0 COMMENT '1=30分開始（料金の時間帯も30分遅らせる）';
UPDATE studio_room SET half_start = 0;
