-- =====================================================================
--  095_studio_room_shift30.sql — 部屋ごとの「30分始まり」（料金の時間帯を30分遅らせる）
-- =====================================================================
--  shift30 … 1 = 毎時30分から始まる部屋（9:30 開始など）。料金表・パックの時間帯を、表示とシミュレーションで30分遅らせる
--            0 = 毎時ちょうど（既定。今までと同じ）
--  DB に入れている料金の時間帯はそのまま（10:00〜18:00 のまま）。画面で読むときにだけ +30 分する
--  ★ このSQLを本番DBで流してから、コードをデプロイすること（先にデプロイすると部屋の SELECT が列なしで失敗する）
-- =====================================================================
ALTER TABLE studio_room
    ADD COLUMN shift30 TINYINT(1) UNSIGNED NOT NULL DEFAULT 0 COMMENT '1=30分始まり（料金の時間帯を30分遅らせる）' AFTER half_unit;
