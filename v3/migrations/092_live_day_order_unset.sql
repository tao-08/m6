-- =====================================================================
--  092_live_day_order_unset.sql — 出演順が未確定の日程の印
-- =====================================================================
--  1 = 名簿だけを取り込み、タイムテーブルの手入力をスキップして登録した（名簿の順に並んでいるだけ）
--      → 最後のバンドはトリではないので、🐔 もトリ回数も付けない（HEADLINER_SQL / band.php / live.php）
--  0 = 出演順が決まっている（既定）
--  ライブ編集の「トリなし」のチェックでも切り替えられる（登録済みの日程用）
--  タイムテーブルを追加したとき、タイムテーブル編集で時刻を初めて入れたときにも 0 へ戻す
--  ★ このSQLを本番DBで流してから、コードをデプロイすること（先にデプロイするとトリの集計が列なしで失敗する）
-- =====================================================================
ALTER TABLE live_day
    ADD COLUMN order_unset TINYINT(1) UNSIGNED NOT NULL DEFAULT 0 COMMENT '1=出演順が未確定（トリなし）' AFTER total_bands;
