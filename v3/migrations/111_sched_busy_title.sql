-- =====================================================================
--  111_sched_busy_title.sql — 日程調整：iCal から取り込んだ予定の「タイトル」を、本人にだけ見せるために保存する
-- =====================================================================
--  110_sched_live_id.sql まで流した DB に、追加で流す。
--  （これから新しく作る人は schema.sql に含まれているので不要）
--  ★ このSQLを本番DBで流してから、コードをデプロイすること（先にデプロイすると、iCal の読み込みが「列が無い」エラーになる）
--
--  今まで iCal の予定は「開始と終了」だけ保存して、タイトルは捨てていた。
--  → 本人が自分のマイスケジュールで「どの予定か」わかるように、タイトルも保存する。
--     ただし中身は個人情報なので暗号化して入れる（lib/sched_ical.php の sched_ical_encrypt。URL と同じ鍵）。
--     他の人には今まで通り「予定あり」としか見せない（復号するのは本人のときだけ）
--
--  sched_busy.title … 暗号化した予定のタイトル。NULL = タイトル無し（手入力・タイトルの無い予定）
--    暗号化すると元より長くなる（base64 で約 1.4 倍 + 数十文字）ので、タイトル 100 文字ぶんが入る 600 文字にしてある
-- =====================================================================
SET NAMES utf8mb4;

ALTER TABLE sched_busy ADD COLUMN title VARCHAR(600) NULL COMMENT '暗号化した予定のタイトル（iCal のみ。本人だけに見せる）' AFTER source;
